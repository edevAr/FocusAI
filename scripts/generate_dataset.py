def main() -> None:
    rows = []
    for text in PRODUCTIVO:
        rows.append((text, "Productivo"))
    for text in PROCRASTINACION:
        rows.append((text, "Procrastinación"))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, quoting=csv.QUOTE_MINIMAL)
        writer.writerow(["texto", "etiqueta"])
        writer.writerows(rows)

    n = len(rows)
    print(f"Dataset escrito en {OUT}")
    print(f"Total: {n} | Productivo: {len(PRODUCTIVO)} | Procrastinación: {len(PROCRASTINACION)}")


if __name__ == "__main__":
    main()
